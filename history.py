# ---------------- helpers ----------------

def log(*a):
    print(*a, file=sys.stderr, flush=True)


def flat(text):
    """Typographic normalisation used for regexes (not for quotes: those go through verify_quote)."""
    t = unicodedata.normalize("NFKC", html.unescape(text or ""))
    for a, b in (("‑", "-"), ("‐", "-"), ("–", "-"), ("’", "'"), (" ", " "),
                 (" ", " "), (" ", " ")):
        t = t.replace(a, b)
    return re.sub(r"\s+", " ", t)


def fold(text):
    """Lowercase, accents removed: for keyword matching only."""
    t = unicodedata.normalize("NFD", flat(text).lower())
    return "".join(c for c in t if unicodedata.category(c) != "Mn")


def fetch(url):
    """GET with a disk cache under data/raw/senat; None on 404."""
    RAW.mkdir(parents=True, exist_ok=True)
    path = RAW / hashlib.sha1(url.encode()).hexdigest()[:20]
    if path.with_suffix(".404").exists():
        return None
    if path.exists():
        return path.read_bytes()
    last = None
    for attempt in range(8):
        if attempt:
            time.sleep(min(2 * attempt, 10))
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (open-data research script)"})
            with urllib.request.urlopen(req, timeout=180) as r:
                data = r.read()
            path.write_bytes(data)
            return data
        except urllib.error.HTTPError as e:
            if e.code in (404, 410):
                path.with_suffix(".404").write_text(url)
                return None
            last = e
        except Exception as e:  # IncompleteRead, reset, timeout
            last = e
    raise RuntimeError(f"{url}: {last}")


def page(url):
    data = fetch(url)
    if data is None:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return data.decode("latin-1")



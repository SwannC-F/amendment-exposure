def load_inputs(folder, session, texte):
    amds = json.loads((folder / "amendments.json").read_text())
    measures = json.loads((folder / "measures.json").read_text())
    if isinstance(measures, dict):
        measures = measures.get("measures", measures)
    effects = {}
    cpath = folder / "criteria.json"
    if cpath.exists():
        crit = json.loads(cpath.read_text())
        items = crit.items() if isinstance(crit, dict) else ((c.get("number"), c) for c in crit)
        for num, c in items:
            c = c or {}
            e = c.get("effect") or (c.get("criteria") or {}).get("effect")
            if e:
                effects[str(num)] = e
    for a in amds:
        a["_text"] = flat(a.get("text") or a.get("dispositif") or "")
        a["_purpose"] = flat(a.get("purpose") or a.get("objet") or "")
        if str(a["number"]) not in effects and a.get("criteria", {}).get("effect"):
            effects[str(a["number"])] = a["criteria"]["effect"]
    for m in measures:
        m["amendments"] = [str(x) for x in m.get("amendments", [])]
        m["effects"] = m.get("effects") or sorted({effects[x] for x in m["amendments"] if x in effects})
    title, dossier = None, None
    tpath = folder / "text.json"
    if tpath.exists():
        t = json.loads(tpath.read_text())
        title, dossier = t.get("title"), t.get("dossier") or t.get("dossier_url")
    return amds, measures, title, dossier


def dossier_of(session, texte):
    """Dossier législatif of a Sénat text, from its amendments home page; (url, title, stages)."""
    acc = page(f"https://www.senat.fr/amendements/{session}/{texte}/accueil.html")
    if not acc:
        return None, None, []
    m = re.search(r'href="((?:https?:)?//www\.senat\.fr/dossier-legislatif/[\w-]+\.html|/dossier-legislatif/[\w-]+\.html)"', acc)
    if not m:
        return None, None, []
    url = m.group(1)
    url = "https:" + url if url.startswith("//") else ("https://www.senat.fr" + url if url.startswith("/") else url)
    d = page(url) or ""
    t = re.search(r"<title>([^<]*)</title>", d)
    title = flat(t.group(1)).replace(" - Sénat", "").strip() if t else None
    stages = []
    for comm, s, n in re.findall(r"amendements/(commissions/)?(\d{4}-\d{4})/(\d+)/accueil\.html", d):
        st = (s, n, "commission" if comm else "seance")
        if st not in stages:
            stages.append(st)
    return url, title, stages


# ---------------- articles cited by the amendments ----------------

NUM = r"(?:[LRDA]\.?\s?\*?)?\d+(?:-\d+)*(?:\s(?:bis|ter|quater|quinquies|sexies|A|B|C|D))?"
ART_RE = re.compile(
    r"\barticles?\s+((?:" + NUM + r")(?:\s*(?:,|et|à|ou)\s*(?:" + NUM + r"))*)"
    r"\s+(?:(?:du|de ce)\s+même\s+code|(?:du|de la|de l'|des)\s*(code\b[^,.;:()«»\"]*))", re.I)


@lru_cache(None)
def code_titles():
    resp = LF.post("/list/code", {"pageSize": 200, "pageNumber": 1, "states": ["VIGUEUR"]})
    return tuple(sorted({r["titre"] for r in resp.get("results") or [] if r.get("titre")}, key=len, reverse=True))


def cited_articles(text, codes):
    """[(code title, article number in Légifrance form)] cited in an amendment text."""
    out, last = [], None
    for m in ART_RE.finditer(flat(text)):
        nums, tail = m.group(1), m.group(2)
        if tail is None:
            code = last
        else:
            low = tail.lower().strip()
            code = next((c for c in codes if low.startswith(c.lower())), None)
        if not code:
            continue
        last = code
        letter = None
        for raw in re.findall(NUM, nums):
            raw = raw.strip()
            mm = re.match(r"([LRDA])\.?\s?\*?(.*)", raw)
            if mm:
                letter, rest = mm.group(1), mm.group(2)
            else:
                rest = raw
            rest = re.sub(r"\s+", " ", rest).strip()
            if not re.match(r"\d", rest):
                continue
            num = (letter or "") + rest.replace(" ", " ")
            if (code, num) not in out:
                out.append((code, num))
    return out


BARE_RE = re.compile(r"\barticles?\s+((?:[LRD]\.?\s?\*?\d+(?:-\d+)*)(?:\s*(?:,|et|à|ou)\s*(?:" + NUM + r"))*)"
                     r"(?:\s+(?:(?:du|de ce)\s+même\s+code|(?:du|de la|de l'|des)\s*(code\b[^,.;:()«»\"]*)))?", re.I)
NEWART_RE = re.compile(r"^«?\s*Art\.\s*([LRD])\.?\s?(\d+(?:-\d+)*)", re.I)


def match_code(tail, codes):
    low = (tail or "").lower().strip()
    return next((c for c in codes if low.startswith(c.lower())), None) if low else None


def split_nums(nums):
    out, letter = [], None
    for raw in re.findall(NUM, nums):
        mm = re.match(r"([LRDA])\.?\s?\*?(.*)", raw.strip())
        letter, rest = (mm.group(1), mm.group(2)) if mm else (letter, raw.strip())
        rest = re.sub(r"\s+", " ", rest).strip()
        if re.match(r"\d", rest):
            out.append((letter or "") + rest)
    return out


def bill_text(session, texte, dossier_url):
    """Texte du Sénat as {bill article key: {alinéa number: [(code, article)]}}.

    Each alinéa inherits the code article it modifies: the last article named outside quotes
    ("1° L'article L. 3262-1 est ainsi modifié"), or the article being written ("« Art. L. 3262-5-2. –")."""
    kind = re.search(r"/dossier-legislatif/([a-z]+)\d", dossier_url or "")
    yy = session[2:4]
    urls = [f"https://www.senat.fr/leg/{k}{yy}-{int(texte):03d}.html" for k in ([kind.group(1)] if kind else []) + ["ppl", "pjl"]]
    raw, url = None, None
    for u in dict.fromkeys(urls):
        raw = page(u)
        if raw:
            url = u
            break
    if not raw:
        return {}, None
    codes = code_titles()
    out = defaultdict(dict)
    code_ctx, art_ctx, cur = None, [], None
    for cls, body in re.findall(r'<tr class="([^"]*)"(.*?)</tr>', raw, re.S):
        m = re.match(r"\s*(article-[\w-]+)", cls)
        if not m:
            continue
        if m.group(1) != cur:
            cur, art_ctx = m.group(1), []
        past = re.findall(r'data-pastille="(\d+)"', body)
        text = flat(re.sub(r"<[^>]+>", " ", re.sub(r"<!--.*?-->", "", body, flags=re.S)))
        text = "".join(c for c in text if unicodedata.category(c) != "Co").strip(" >")
        if not past:
            continue
        quoted = text.startswith("«")
        new = NEWART_RE.match(text)
        if new:
            art_ctx = [(code_ctx, new.group(1).upper() + new.group(2))] if code_ctx else art_ctx
        elif not quoted:
            found = []
            for mm in BARE_RE.finditer(text):
                code = match_code(mm.group(2), codes) or code_ctx
                if mm.group(2) and code:
                    code_ctx = code
                found += [(code, n) for n in split_nums(mm.group(1)) if code]
            if not found:
                for mm in re.finditer(r"(?:du|de la|de l'|des)\s+(code\b[^,.;:()«»\"]*)", text):
                    code_ctx = match_code(mm.group(1), codes) or code_ctx
            else:
                art_ctx = list(dict.fromkeys(found))
        out[cur][int(past[0])] = list(art_ctx)
    return dict(out), url


def bill_key(article_field):
    m = re.search(r"^article\s+(.+?)\s*(?:\(.*\))?$", (article_field or "").strip(), re.I)
    return "article-" + re.sub(r"\s+", "-", m.group(1).strip().lower()) if m else None


def alineas(text):
    out = []
    for m in re.finditer(r"alin[ée]as?\s+(\d+(?:\s*(?:,|et|à)\s*\d+)*)", flat(text), re.I):
        part = m.group(1)
        nums = [int(x) for x in re.findall(r"\d+", part)]
        if " à " in part and len(nums) == 2:
            nums = list(range(nums[0], nums[1] + 1))
        out += nums
    return out


def amendment_articles(a, bill, codes):
    """Code articles an amendment bears on: those it cites, plus those of the bill alinéas it amends."""
    arts = cited_articles(a["_text"], codes)
    key = bill_key(a.get("article"))
    if key and key in bill:
        nums = alineas(a["_text"])
        sel = [bill[key].get(n, []) for n in nums] if nums else list(bill[key].values())
        for lst in sel:
            for c in lst:
                if c not in arts:
                    arts.append(c)
    return arts


def art_label(code, num):
    m = re.match(r"([LRDA])(.*)", num)
    n = f"{m.group(1)}. {m.group(2)}" if m else num
    return f"article {n} du {code[0].lower() + code[1:]}"



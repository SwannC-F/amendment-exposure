def senat_candidates(session, texte, stages, laws_docs):
    """Ordered list of (session, number, stage, origin) to scan."""
    out = [(s, n, st, "dossier en cours") for s, n, st in stages if not (s == session and n == texte and st == "seance")]
    for d, origin in laws_docs:
        for st in ("commission", "seance"):
            key = (d["session"], d["num"], st)
            if key[:2] == (session, texte) or any(o[:3] == key for o in out):
                continue
            out.append((*key, origin))
    out.sort(key=lambda x: x[0], reverse=True)
    return out[:MAX_SENAT_TEXTS * 2]


def ameli(cands, articles, rx, codes):
    """Rows of past amendments relevant to the followed articles or the search terms."""
    followed = set(articles)
    hist = AM.group_history()
    scanned, keep = [], []
    for session, n, stage, origin in cands:
        try:
            rows = ameli_rows(session, n, stage)
        except Exception as e:
            log("ameli download failed", session, n, stage, e)
            scanned.append({"session": session, "number": n, "stage": stage, "origin": origin,
                            "csv": AM.csv_url(session, n, stage), "error": str(e)})
            continue
        if rows is None:
            continue
        hit = 0
        for r in rows:
            disp, obj = flat(AM.clean(r.get("Dispositif"))), flat(AM.clean(r.get("Objet")))
            if not (rx and rx.search(fold(disp + " " + obj))):
                continue
            cites = [a for a in cited_articles(disp, codes) if a in followed]
            num = r.get("Numéro", "").strip()
            filed = r.get("Date de dépôt", "")
            m = re.search(r"(\d{5}[a-z])\.html", r.get("Fiche Sénateur", ""))
            group, gsrc = (AM.group_at(hist, m.group(1), filed), "history") if m else (None, None)
            if not group and "groupe" in r.get("Au nom de", "").lower():
                group, gsrc = r["Au nom de"], "amendment"
            url = r.get("Url amendement", "")
            url = "https:" + url if url.startswith("//") else url
            keep.append({"id": f"senat:{session}/{n}/{num}", "session": session, "text_number": n, "stage": stage,
                         "number": num, "filed": filed, "year": int(filed[:4]) if filed[:4].isdigit() else None,
                         "author": r.get("Auteur", ""), "group": group or "", "group_source": gsrc or "unknown",
                         "outcome": AM.outcome(r.get("Sort", "")), "url": url,
                         "cites": [art_label(*a) for a in cites], "dispositif": disp, "objet": obj})
            hit += 1
        scanned.append({"session": session, "number": n, "stage": stage, "origin": origin,
                        "csv": AM.csv_url(session, n, stage), "rows": len(rows), "relevant": hit})
        log(f"ameli {session}/{n} {stage}: {len(rows)} rows, {hit} relevant ({origin})")
    return scanned, keep


def resolve_key(k, keys):
    """The measure key the LLM meant: exact, else a close spelling (it sometimes alters a letter)."""
    if not isinstance(k, str) or not k:
        return None
    if k in keys:
        return k
    close = difflib.get_close_matches(k, list(keys), n=1, cutoff=0.85)
    return close[0] if close else None


def measures_brief(measures):
    return [{"key": m["key"], "theme": m["theme"], "effects": m["effects"][:4]} for m in measures]


def map_ameli(measures, past):
    system = ("Tu es analyste parlementaire. Tu rattaches des amendements déposés au Sénat dans le passé aux mesures "
              "d'un texte examiné aujourd'hui. Tu ne rattaches que si l'amendement porte clairement sur le même objet "
              "que la mesure ; un amendement rédactionnel, de coordination ou portant sur un autre aspect du même article "
              "n'est rattaché à aucune mesure (null). Réponds en JSON uniquement.")
    keys = {m["key"] for m in measures}

    def run(batch):
        user = json.dumps({
            "consigne": ("Pour chaque amendement passé, indique la mesure actuelle (clé) sur laquelle il porte, ou null. "
                         "stance : « pour » si l'amendement allait dans le sens de la mesure, « contre » s'il allait en sens "
                         "inverse, « neutre » sinon. quote : un extrait COPIÉ MOT POUR MOT du texte de l'amendement "
                         "(20 à 200 caractères) qui justifie le rattachement. Format : "
                         "{\"results\": [{\"id\": \"...\", \"measure\": \"clé|null\", \"stance\": \"pour|contre|neutre\", \"quote\": \"...\"}]}"),
            "mesures_actuelles": measures_brief(measures),
            "amendements_passes": [{"id": a["id"], "texte": (a["dispositif"][:900] + " || OBJET : " + a["objet"][:500])}
                                   for a in batch]}, ensure_ascii=False)
        try:
            ans = chat_json(system, user, max_tokens=8000)
        except Exception as e:
            log("ameli LLM batch failed", e)
            return []
        return (ans.get("results") if isinstance(ans, dict) else ans) or []

    batches = [past[i:i + AMELI_BATCH] for i in range(0, len(past), AMELI_BATCH)]
    with ThreadPoolExecutor(PARALLEL) as ex:
        results = [r for rs in ex.map(run, batches) for r in rs]
    by_id = {a["id"]: a for a in past}
    mapped, rejected = [], 0
    for r in results:
        a = by_id.get(r.get("id"))
        r["measure"] = resolve_key(r.get("measure"), keys)
        if not a or not r["measure"]:
            continue
        q = (r.get("quote") or "").strip()
        if not verify_quote(q, a["dispositif"], a["objet"]):
            rejected += 1
            continue
        mapped.append({**{k: v for k, v in a.items() if k not in ("dispositif", "objet")},
                       "measure": r["measure"], "stance": r.get("stance") if r.get("stance") in ("pour", "contre") else "neutre",
                       "quote": q})
    return mapped, rejected



def legifrance(articles, refs, fams):
    """Versions and modifying texts of each followed article, plus derogating law articles.
    Articles outside the families the text modifies get their version in force only."""
    out, texts = {}, {}
    for code, num in articles:
        try:
            aid = LF.find_article(num, code)
        except Exception as e:
            log("legifrance search failed", code, num, e)
            aid = None
        key = f"{code}|{num}"
        if not aid:
            out[key] = {"code": code, "num": num, "label": art_label(code, num), "found": False}
            continue
        try:
            cur = LF.get_article(aid)
        except Exception as e:
            log("legifrance getArticle failed", code, num, e)
            out[key] = {"code": code, "num": num, "label": art_label(code, num), "found": False, "error": str(e)}
            continue
        versions = []
        core = in_family((code, num), fams)
        vlist = sorted(cur.get("articleVersions") or [], key=lambda v: v["dateDebut"] or 0)
        if not core:
            vlist = [v for v in vlist if v["id"] == aid] or vlist[-1:]
        for v in vlist:
            if not v["id"].startswith("LEGIARTI"):
                continue
            try:
                full = LF.get_article(v["id"])
            except Exception as e:
                log("legifrance version failed", v["id"], e)
                continue
            start = LF.day(v["dateDebut"])
            mod = LF.modifier_of(full, start)
            entry = {"version_id": v["id"], "start": start, "end": LF.day(v["dateFin"]), "etat": v["etat"],
                     "url": LF.article_url(v["id"]), "modified_by": None}
            if mod and mod.get("textCid"):
                cid = mod["textCid"]
                entry["modified_by"] = {"id": cid, "link_type": mod.get("linkType"),
                                        "article": LF.clean(mod.get("textTitle")).split(" - ", 1)[-1]}
                texts.setdefault(cid, set()).add(key)
            versions.append(entry)
        out[key] = {"code": code, "num": num, "label": art_label(code, num), "found": True, "id": aid,
                    "url": LF.article_url(aid), "versions": versions, "complete_history": core,
                    "n_versions": len(cur.get("articleVersions") or []),
                    "derogations": derogations(cur, num) if core else []}
        refs[f"legifrance:{aid}"] = {"source": "Légifrance", "label": art_label(code, num), "url": LF.article_url(aid)}
        for d in out[key]["derogations"]:
            refs[f"legifrance:{d['id']}"] = {"source": "Légifrance", "label": d["label"], "url": d["url"]}
            for v in d["versions"]:
                if v.get("modified_by"):
                    texts.setdefault(v["modified_by"]["id"], set()).add(key)
    info = {}
    for cid in texts:
        try:
            j = LF.post("/consult/jorf", {"textCid": cid})
        except Exception as e:
            log("jorf failed", cid, e)
            continue
        prep = LF.clean(j.get("prepWork") or "")
        info[cid] = {"id": cid, "title": LF.clean(j.get("title") or ""), "nor": j.get("nor"),
                     "date": LF.day(j["dateTexte"]) if isinstance(j.get("dateTexte"), int) else None,
                     "url": LF.text_url(cid), "senat_documents": LF.senat_texts(prep),
                     "articles": sorted(texts[cid])}
        refs[f"legifrance:{cid}"] = {"source": "Légifrance", "label": info[cid]["title"], "url": LF.text_url(cid),
                                     "date": info[cid]["date"]}
    for a in out.values():
        for v in a.get("versions", []):
            mb = v.get("modified_by")
            if mb and mb["id"] in info:
                mb.update(title=info[mb["id"]]["title"], date=info[mb["id"]]["date"], url=info[mb["id"]]["url"])
    return out, info


def derogations(cur, num):
    """Non-codified law articles in force citing this article and saying 'par dérogation'."""
    found = []
    digits = re.sub(r"^[LRDA]", "", num)
    for link in (cur.get("lienCitations") or [])[:MAX_CITATIONS]:
        aid = link.get("articleId") or ""
        if link.get("natureText") != "LOI" or not aid.startswith("LEGIARTI"):
            continue
        try:
            art = LF.get_article(aid)
        except Exception:
            continue
        txt = flat(LF.clean(art.get("texte")))
        if "dérogation" not in txt.lower() or digits not in txt:
            continue
        if art.get("etat") not in (None, "VIGUEUR"):
            continue
        label = re.sub(r"^LOI", "Loi", LF.clean(link.get("textTitle")).split(" - ")[0]) + f" - art. {art.get('num')}"
        if any(f["label"] == label for f in found):
            continue
        vs = []
        for av in sorted(art.get("articleVersions") or [], key=lambda x: x["dateDebut"] or 0):
            if not av["id"].startswith("LEGIARTI"):
                continue
            try:
                full = LF.get_article(av["id"])
            except Exception:
                continue
            start = LF.day(av["dateDebut"])
            mod = LF.modifier_of(full, start) or {"textCid": link.get("textCid"), "linkType": "CREATION"}
            vs.append({"version_id": av["id"], "start": start, "end": LF.day(av["dateFin"]), "etat": av["etat"],
                       "text": flat(LF.clean(full.get("texte")))[:600],
                       "modified_by": {"id": mod.get("textCid"), "link_type": mod.get("linkType")}})
        found.append({"id": aid, "label": label, "url": f"https://www.legifrance.gouv.fr/loda/article_lc/{aid}",
                      "text": txt[:600], "versions": vs})
    return found


def title_laws(terms):
    """Laws whose title contains a search term (Légifrance LODA)."""
    cids = {}
    for term in terms:
        body = {"recherche": {"champs": [{"typeChamp": "TITLE", "criteres": [
            {"typeRecherche": "TOUS_LES_MOTS_DANS_UN_CHAMP", "valeur": term, "operateur": "ET"}], "operateur": "ET"}],
            "filtres": [{"facette": "NATURE", "valeurs": ["LOI"]}], "pageNumber": 1, "pageSize": 10,
            "operateur": "ET", "sort": "SIGNATURE_DATE_DESC", "typePagination": "DEFAUT"}, "fond": "LODA_DATE"}
        try:
            resp = LF.post("/search", body)
        except Exception as e:
            log("title search failed", term, e)
            continue
        for r in resp.get("results") or []:
            for t in r.get("titles") or []:
                if t.get("cid"):
                    cids[t["cid"]] = LF.clean(t.get("title"))
    return cids



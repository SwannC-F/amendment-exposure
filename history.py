"""History of the measures of any Sénat text: Légifrance, Ameli (past Sénat amendments), HATVP.

    python3 history.py <session> <texte>            # works in data/<session>/<texte>/
    python3 history.py <session> <texte> --dir PATH # same, other folder (tests, fixtures)

Reads amendments.json and measures.json (criteria.json and text.json when present) and writes
history.json, keyed by measure key. Nothing is written by hand for a given topic:

- Légifrance: the code articles to follow are the ones the amendments cite ("article L. 3262-3 du code
  du travail", "article 81 du code général des impôts", "du même code"), matched against the list of
  codes returned by Légifrance. For each article, every version and the text that made it; plus the
  non-codified law articles in force that derogate from it (lienCitations of the current version).
- Ameli: past Sénat texts are (1) the other stages of the current dossier (commission), (2) the Sénat
  documents listed in the travaux préparatoires of the laws that modified the followed articles, and
  (3) of the laws whose title matches the search terms. Their amendments that cite a followed article
  or a search term are attached to the CURRENT measures by the LLM, in batches, with a verbatim quote
  of the amendment checked by code. Outcome comes from the Ameli "Sort" column; the group is the
  author's group on the filing date (data.senat.fr ODSEN_HISTOGROUPES).
- HATVP: search terms come from the bill title and the measure themes (one LLM call, synonyms
  allowed) plus the followed article numbers. Matching fiches are read by the LLM, which keeps a side
  only when the declared text states it, with a verbatim excerpt checked by code. Organisations that
  declared both sides on a measure go to lobby_both.

Every finding is generated by code from the collected data and cites refs present in the file's `refs`.
"""

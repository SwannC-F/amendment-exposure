def hatvp_fiches(rx):
    HV.download(False)
    data = json.load(open(HV.RAW, encoding="utf-8"))["publications"]
    fiches = {}
    for p in data:
        sid = p.get("identifiantNational")
        cat = p.get("categorieOrganisation", {}) or {}
        for ex in p.get("exercices", []):
            pc = ex.get("publicationCourante", {})
            for a in pc.get("activites") or []:
                ac = a["publicationCourante"]
                text = HV.activity_text(ac)
                if not rx.search(fold(text)):
                    continue
                aris = ac.get("actionsRepresentationInteret", [])
                fiches[ac["identifiantFiche"]] = {
                    "fiche": ac["identifiantFiche"], "org": HV.norm(p["denomination"]), "hatvp_id": sid,
                    "category": cat.get("label"), "consultancy": cat.get("code") in HV.CONSULTANCY_CODES,
                    "year": int(pc["dateDebut"][-4:]), "text": text,
                    "on_behalf_of": sorted({HV.norm(t) for x in aris for t in x.get("tiers", [])})}
    return fiches, HV.file_date()


def map_hatvp(measures, fiches):
    system = ("Tu lis des déclarations d'activité du répertoire des représentants d'intérêts (HATVP). Tu indiques la "
              "position déclarée sur des mesures d'un texte du Sénat UNIQUEMENT quand le texte déclaré l'énonce "
              "(demander, soutenir, s'opposer, limiter…). Une simple mention du sujet n'est pas une position. "
              "Réponds en JSON uniquement.")
    keys = {m["key"] for m in measures}

    def run(batch):
        user = json.dumps({
            "consigne": ("Pour chaque fiche, liste les positions déclarées sur les mesures (une fiche peut en avoir "
                         "plusieurs, ou aucune). side : « pour » si l'organisation demande ce que fait la mesure, "
                         "« contre » si elle demande l'inverse. quote : extrait COPIÉ MOT POUR MOT de la fiche (20 à 200 "
                         "caractères) qui énonce la position. Format : {\"results\": [{\"fiche\": \"...\", \"measure\": \"clé\", "
                         "\"side\": \"pour|contre\", \"quote\": \"...\"}]}"),
            "mesures": measures_brief(measures),
            "fiches": [{"fiche": f["fiche"], "organisation": f["org"], "texte": f["text"][:1200]} for f in batch]},
            ensure_ascii=False)
        try:
            ans = chat_json(system, user, max_tokens=8000)
        except Exception as e:
            log("hatvp LLM batch failed", e)
            return []
        return (ans.get("results") if isinstance(ans, dict) else ans) or []

    items = sorted(fiches.values(), key=lambda f: (-f["year"], f["fiche"]))
    batches = [items[i:i + HATVP_BATCH] for i in range(0, len(items), HATVP_BATCH)]
    with ThreadPoolExecutor(PARALLEL) as ex:
        results = [r for rs in ex.map(run, batches) for r in rs]
    sides, rejected, seen = [], 0, set()
    for r in results:
        f = fiches.get(r.get("fiche"))
        r["measure"] = resolve_key(r.get("measure"), keys)
        if not f or not r["measure"] or r.get("side") not in ("pour", "contre"):
            continue
        q = (r.get("quote") or "").strip()
        if not verify_quote(q, f["text"]):
            rejected += 1
            continue
        k = (f["fiche"], r["measure"], r["side"])
        if k in seen:
            continue
        seen.add(k)
        sides.append({"fiche": f["fiche"], "measure": r["measure"], "side": r["side"], "quote": q})
    return sides, rejected



def search_terms(title, measures):
    system = ("Tu prépares des recherches plein texte dans des registres publics français (lobbying HATVP, "
              "titres de lois). Réponds en JSON uniquement.")
    user = json.dumps({
        "consigne": ("À partir du titre du texte et des thèmes de ses mesures, donne 3 à 10 expressions de recherche "
                     "propres au sujet du texte : le nom de l'objet réglementé et ses synonymes ou appellations courantes "
                     "(y compris marques devenues génériques). Pas de mots généraux seuls (« commission », « plafond », "
                     "« salarié », « entreprise »). Format : {\"terms\": [\"...\"]}"),
        "titre": title, "themes": [m["theme"] for m in measures]}, ensure_ascii=False)
    ans = chat_json(system, user)
    terms = [t.strip() for t in (ans.get("terms") if isinstance(ans, dict) else ans) or [] if isinstance(t, str)]
    return [t for t in dict.fromkeys(terms) if len(t) >= 4][:10]


def families(bill, articles_by_amd):
    """(code, 'L3262')-like families of the articles the text itself modifies (bill alinéas); without
    a bill text, those cited by at least two amendments."""
    arts = [a for al in bill.values() for lst in al.values() for a in lst]
    if not arts:
        count = defaultdict(int)
        for lst in articles_by_amd.values():
            for a in set(lst):
                count[a] += 1
        arts = [a for a, n in count.items() if n >= 2]
    out = []
    for code, num in arts:
        m = re.match(r"([LRD]?\d+)", num)
        if m and (code, m.group(1)) not in out:
            out.append((code, m.group(1)))
    return out


def in_family(art, fams):
    code, num = art
    return any(code == c and re.match(re.escape(f) + r"(?:-|$)", num) for c, f in fams)


def term_regex(terms, fams):
    parts = []
    for t in terms:
        words = re.split(r"[\s\-']+", fold(t))
        parts.append(r"[\s\-']?".join(re.escape(w) + r"[sx]?" for w in words if w))
    for code, fam in fams:
        m = re.match(r"([LRD])(\d+)", fam)
        if m:  # 'L. 3262' family of the articles the text modifies: specific enough
            parts.append(m.group(1).lower() + r"\.?\s?" + m.group(2) + r"\b")
    return re.compile("|".join(f"(?:{p})" for p in parts)) if parts else None


